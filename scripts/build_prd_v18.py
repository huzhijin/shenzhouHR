def normalize_document_fonts(doc: Document) -> None:
    """Use a locally available CJK font for every style and run.

    The V1.7 helper defaults to Arial Unicode MS, which is not present on a
    standard current macOS installation and therefore renders Chinese as tofu
    in headless LibreOffice.  Applying the same embeddable CJK family to all
    font slots also avoids mixed-script substitution differences between Word
    and LibreOffice.
    """
    for style in doc.styles:
        if style.element.rPr is None:
            style.element.insert(0, OxmlElement("w:rPr"))
        r_pr = style.element.rPr
        r_fonts = r_pr.find(qn("w:rFonts"))
        if r_fonts is None:
            r_fonts = OxmlElement("w:rFonts")
            r_pr.insert(0, r_fonts)
        for slot in ("ascii", "hAnsi", "eastAsia", "cs"):
            r_fonts.set(qn(f"w:{slot}"), DOC_FONT)
        if hasattr(style, "font"):
            style.font.name = DOC_FONT

    roots = [doc.element]
    for section in doc.sections:
        roots.extend([section.header._element, section.footer._element])
    seen = set()
    for root in roots:
        root_id = id(root)
        if root_id in seen:
            continue
        seen.add(root_id)
        for run in root.iter(qn("w:r")):
            r_pr = run.find(qn("w:rPr"))
            if r_pr is None:
                r_pr = OxmlElement("w:rPr")
                run.insert(0, r_pr)
            r_fonts = r_pr.find(qn("w:rFonts"))
            if r_fonts is None:
                r_fonts = OxmlElement("w:rFonts")
                r_pr.insert(0, r_fonts)
            for slot in ("ascii", "hAnsi", "eastAsia", "cs"):
                r_fonts.set(qn(f"w:{slot}"), DOC_FONT)


