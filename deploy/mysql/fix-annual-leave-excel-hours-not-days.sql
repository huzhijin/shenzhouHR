CREATE TEMPORARY TABLE tmp_annual_unitfix_resolved AS
SELECT
    src.employee_number,
    src.display_name,
    src.delta_hours,
    src.target_opening_hours,
    employee.employee_id,
    account.time_account_id,
    account.policy_version_id,
    CONCAT('CUTOVER20260801:ANNUAL_LEAVE_UNITFIX:', src.employee_number) AS request_id
FROM tmp_annual_unitfix src
JOIN employee employee
  ON employee.employee_number = src.employee_number
JOIN time_account account
  ON account.employee_id = employee.employee_id
 AND account.account_type = 'ANNUAL_LEAVE'
 AND account.account_year = 2026
WHERE src.delta_hours <> 0;

