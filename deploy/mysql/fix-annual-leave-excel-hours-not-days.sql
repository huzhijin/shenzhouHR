INSERT IGNORE INTO time_account_ledger_entry (
    time_account_ledger_entry_id,
    time_account_id,
    sequence_no,
    entry_type,
    amount_hours,
    source_type,
    source_id,
    business_date,
    effective_from,
    expires_on,
    policy_version_id,
    period_version_id,
    close_snapshot_id,
    request_id,
    reversal_of_entry_id,
    actor_id,
    occurred_at
)
SELECT
    UUID(),
    resolved.time_account_id,
    COALESCE(seq.max_seq, 0) + 1,
    'ADJUSTMENT',
    resolved.delta_hours,
    'HR_MANUAL_ADJUSTMENT',
    resolved.request_id,
    DATE '2026-08-01',
    DATE '2026-08-01',
    DATE '2026-12-31',
    resolved.policy_version_id,
    NULL,
    NULL,
    resolved.request_id,
    NULL,
    'SYSTEM',
    CURRENT_TIMESTAMP(6)
FROM tmp_annual_unitfix_resolved resolved
LEFT JOIN (
    SELECT time_account_id, MAX(sequence_no) AS max_seq
    FROM time_account_ledger_entry
    GROUP BY time_account_id
) seq ON seq.time_account_id = resolved.time_account_id;

UPDATE time_account account
JOIN (
    SELECT entry.time_account_id, SUM(entry.amount_hours) AS ledger_hours
    FROM time_account_ledger_entry entry
    GROUP BY entry.time_account_id
) ledger ON ledger.time_account_id = account.time_account_id
JOIN tmp_annual_unitfix_resolved resolved
  ON resolved.time_account_id = account.time_account_id
SET
    account.balance_hours = ledger.ledger_hours,
    account.row_version = account.row_version + 1,
    account.updated_at = CURRENT_TIMESTAMP(6);

